// 悩み起点プログラム（ミッション）= このサイトの新しい主役。
//
// 考え方:
//   飼い主は「200のコマンドを教えたい」のではなく「“この悩み”を解決したい」。
//   そこで【解決したいゴール → 前提条件をたどる依存グラフ(DAG) → 直列ロードマップ】
//   を悩みごとに用意し、毎日1ステップ・短時間でこなせる「日割りプログラム」にする。
//   - 期間は固定ではない。早い子は3日、難しい子は数週間。ただし“1つの塊”は最長1週間まで
//     （長すぎると飽きる）。満足したら続き or 別ミッションへ。
//   - 各日は採点エンジン（levels.ts のレベル）と levelKey で紐づく＝アプリで自動採点できる。
//   - 終わりに必ずテスト。出来で「卒業 / もう一度この塊 / 前の塊に戻る」を分岐させる。
//
// このファイルは Web 表示用の“組み立て指示書”。部品（コマンド/ケア/レベル）は既存データを参照する。

export type StepRefKind = "command" | "care";

// ゴールから前提を遡って直列化した「鎖」の1リンク（依存グラフの可視化用）
export interface MissionChainLink {
  id: string; // commands.ts / careTasks.ts の id（詳細ページへのリンク元）
  kind: StepRefKind;
  label: string; // 表示名（口語）
  role: string; // この前提が「なぜ要るか」一言
}

export interface MissionDay {
  day: number;
  focus: string; // その日の「新しい一歩」の見出し
  minutes: number; // 目安の所要（分）
  refId?: string; // 関連する部品の id（詳細ページへ）
  refKind?: StepRefKind;
  levelKey?: string; // 採点エンジン連携 "id:Ln"（アプリの自動採点用。Webは表示しない）
  // 1セッション＝3部構成（実際のトレーニングのリズム）:
  warmup?: string; // ① おさらい（前日までを軽くやり直す）。初日は省略可
  step: string[]; // ② 今日の新しい一歩（進度を1つだけ上げる）
  cooldown: string; // ③ 成功で終える（必ず簡単なことで成功して終了）
  clear: string; // この日のクリア基準（できたら次へ）
}

export interface MissionTest {
  setup: string; // テストの状況設定
  pass: string; // 合格基準（測定可能に）
  ifPass: string; // 合格したら
  ifFail: string; // 届かなかったら（どの日に戻るか）
}

export interface Mission {
  id: string;
  title: string; // ゴール（口語）
  question: string; // 「○○を直すには、どこから教えればいい？」＝ページH1・導入に使う
  seoTitle: string; // <title>用。検索キーワードを前方に置き、解決ベネフィットを示す
  pain: string; // いまの悩み（検索で来る人の言葉）
  goal: string; // できるようになること（達成像）
  whyHard: string; // なぜ難しいか＝複合性の説明（このサイトの価値の核）
  durationLabel: string; // 例「3〜7日 / 1日15〜20分」
  level: "やさしい" | "ふつう" | "じっくり";
  prepare: string[]; // 用意するもの（始める前に揃える道具）
  stopSigns: string[]; // 犬の「いやだ」サイン＝この手前で引く・1段戻す
  chain: MissionChainLink[]; // ゴール←前提←前提… を遡った鎖（直列化の根拠）
  dailyStart: string; // 毎回まずやる固定のウォームアップ（土台の維持）
  rhythmNote: string; // 毎日のリズム＝おさらい→一歩→成功、進めない日は繰り返す、の説明
  days: MissionDay[]; // 直列の日割りプログラム（各日が前日に積み上がる）
  test: MissionTest;
  safety?: string; // 安全・受診の注意
  relatedProblems?: string[];
  relatedArticles?: string[]; // slug
}

